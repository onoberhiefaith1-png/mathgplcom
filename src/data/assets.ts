  assetCategories.find((c) => c.slug === slug);

export const getSubcategory = (categorySlug?: string, subSlug?: string) => {
  const cat = getCategory(categorySlug);
  return {
    category: cat,
    subcategory: cat?.subcategories.find((s) => s.slug === subSlug),
  };
};
