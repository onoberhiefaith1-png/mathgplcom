// SESSION PAIRING STANDARD — a Solution is its own session.
// Mirror of src/lib/lessonnotes/sessionPairingStandard.ts; keep identical.

export const SESSION_PAIRING_STANDARD = `
MATHGPL SESSION PAIRING STANDARD — a Solution is its own session.

1. Every Example, Exercise, Classwork, Homework or Assessment question that
   requires working is followed IMMEDIATELY by its own Solution session:
   Classwork 1 → Solution 1 → Classwork 2 → Solution 2 → …
2. Never "all questions, then all solutions". Never question and solution in
   one session. Never a question with no Solution session.
3. Solution numbers match their question within each activity
   (Homework 3 → Solution 3).
4. Introduction, Explanation and Summary are teaching content; they never get
   a Solution session.
5. A question may start without the word "Question" or "Classwork" (for example
   "The table shows the marks of 10 students. Calculate the mean."). A solution
   may start without the word "Solution" (for example "Add all the values…").
   Recover both from meaning.
6. A solution that exists anywhere in the note is matched to its own question
   and moved — never rewritten from scratch and never duplicated.
7. Improve wording only; never change numbers, method, the intended answer,
   the difficulty or the question itself.
`.trim();
